def get_blosum50_matrix(normalize: bool = True) -> tuple[list[str], torch.Tensor]:
    """
    Return BLOSUM50 matrix in log space, optionally normalized.

    Args:
        normalize: If True, return normalized BLOSUM50-derived correlation matrix in log space.
            If False, return raw BLOSUM50 matrix in log space. Defaults to True.

    Returns:
        Tuple of (alphabet, matrix) where alphabet is a list of 21 characters
        (20 amino acids + gap) and matrix is a (21, 21) tensor in log space.
    """
    mat = torch.tensor(_BLOSUM50, dtype=torch.float64)
    if normalize:
        diag = mat.diag()
        mat = mat - 0.5 * (diag[:, None] + diag[None, :])
        mat = mat * (0.25 / mat.median().abs())
    return _ALPHABET, mat
